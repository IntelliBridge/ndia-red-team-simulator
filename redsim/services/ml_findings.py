def _same_eps(a: float | None, b: float | None) -> bool:
    return a is not None and b is not None and math.isclose(float(a), float(b), rel_tol=0.0, abs_tol=1e-12)


def _eps_of(measurement: Measurement) -> float | None:
    value = measurement.params.get("eps")
    return float(value) if isinstance(value, (int, float)) and not isinstance(value, bool) else None


def _fraction(numerator: int | None, denominator: int | None) -> str:
    if numerator is None or denominator is None:
        return "not recorded"
    return f"{numerator}/{denominator}"


def _rate(value: float | None) -> str:
    return "not computed" if value is None else f"{float(value):.4f}"


def finding_measurements(campaign: CampaignRecord, attack_id: str) -> list[Measurement]:
    """Spec 5.7: the clean row, this attack's rows per eps and the control rows per eps."""
    return [m for m in campaign.measurements
            if m.family in ("clean", "control") or m.attack_id == attack_id]


def _first_explained_attack(campaign: CampaignRecord, in_scope: Sequence[str]) -> str | None:
    """The first in-scope attack whose reference row carries explain-stage fields.

    The campaign runner numbers observations ``o.NNN`` per attack and suffixes
    ``.<attack_id>`` only on a collision, so the bare ids belong to the first
    attack that was explained. The reference row is the only row the explain
    stage fills (spec 13.5), which is how "was explained" is recognised.
    """
    for aid in in_scope:
        for m in campaign.measurements:
            if m.family == "evasion" and m.attack_id == aid and (
                m.expl_shift_n is not None or m.expl_shift_mean is not None
            ):
                return aid
    return in_scope[0] if in_scope else None


def _observation_owner(obs_id: str, in_scope: Sequence[str], bare_owner: str | None) -> str | None:
    for aid in in_scope:
        if obs_id.endswith(f".{aid}"):
            return aid
    return bare_owner


def finding_observations(campaign: CampaignRecord, attack_id: str) -> list[Observation]:
    """Observations attributed to ``attack_id`` by the runner's id scheme (see above)."""
    in_scope = list(dict.fromkeys(campaign.config.attack_ids))
    bare_owner = _first_explained_attack(campaign, in_scope)
    return [o for o in campaign.observations
            if _observation_owner(o.id, in_scope, bare_owner) == attack_id]


def _cites(ids: Iterable[str], mine: set[str], others: set[str]) -> bool:
    """A statement belongs to this finding when it cites this attack's evidence, or when
    it cites only shared evidence (clean and control rows) and nothing of another attack."""
    cited = set(ids)
    if cited & mine:
        return True
    return not (cited & others)


def _finding_statements(
    campaign: CampaignRecord, attack_id: str, observations: Sequence[Observation],
) -> tuple[list[Interpretation], list[CandidateRecommendation]]:
    in_scope = list(dict.fromkeys(campaign.config.attack_ids))
    bare_owner = _first_explained_attack(campaign, in_scope)
    mine = {m.id for m in campaign.measurements if m.family == "evasion" and m.attack_id == attack_id}
    mine |= {o.id for o in observations}
    others = {m.id for m in campaign.measurements
              if m.family == "evasion" and m.attack_id is not None and m.attack_id != attack_id}
    others |= {o.id for o in campaign.observations
               if _observation_owner(o.id, in_scope, bare_owner) != attack_id}
    interpretation = [i for i in campaign.interpretation if _cites(i.basis, mine, others)]
    mine |= {i.id for i in interpretation}
    others |= {i.id for i in campaign.interpretation if i not in interpretation}
    recommendations = [r for r in campaign.recommendations if _cites(r.triggered_by, mine, others)]
    return interpretation, recommendations


def _evasion_row(measurements: Sequence[Measurement], attack_id: str, eps: float | None) -> Measurement | None:
    if eps is None:
        return None
    for m in measurements:
        if m.family == "evasion" and m.attack_id == attack_id and _same_eps(_eps_of(m), eps):
            return m
    return None


def _control_row(measurements: Sequence[Measurement], eps: float) -> Measurement | None:
    for m in measurements:
        if m.family == "control" and _same_eps(_eps_of(m), eps):
            return m
    return None


def finding_title(attack_name: str, norm: str, inputs: FindingInputs, first_row: Measurement | None) -> str:
    """Spec 5.7 / 15.5 title: attack, first-success eps, norm and the ASR fraction."""
    eps_text = f"{float(inputs.first_success_eps):g}" if inputs.first_success_eps is not None else "n/a"
    flipped = first_row.n_flipped_from_clean if first_row is not None else None
    denominator = (first_row.n_clean_correct if first_row is not None and first_row.n_clean_correct is not None
                   else inputs.n_clean_correct)
    return (f"{attack_name} flips predictions at ε={eps_text} ({norm}; "
            f"ASR {_fraction(flipped, denominator)})")


def finding_description(
    campaign: CampaignRecord, attack_id: str, attack_name: str, inputs: FindingInputs,
    measurements: Sequence[Measurement],
) -> str:
    """Rules-generated measured summary citing measurement ids (spec 5.7). No LLM."""
    config = campaign.config
    ref = float(config.reference_eps)
    clean = next((m for m in measurements if m.family == "clean"), None)
    first_row = _evasion_row(measurements, attack_id, inputs.first_success_eps)
    ref_row = _evasion_row(measurements, attack_id, ref)
    control = _control_row(measurements, ref)
    parts: list[str] = []
    if first_row is not None and inputs.first_success_eps is not None:
        parts.append(
            f"Measured: {attack_name} ({attack_id}, {config.norm}) first crossed the finding threshold "
            f"(ASR >= {inputs.threshold:g}) at eps={float(inputs.first_success_eps):g}, flipping "
            f"{_fraction(first_row.n_flipped_from_clean, first_row.n_clean_correct)} clean-correct samples "
            f"[{first_row.id}]."
        )
    else:
        parts.append(
            f"Measured: {attack_name} ({attack_id}, {config.norm}) crossed the finding threshold "
            f"(ASR >= {inputs.threshold:g}) on the declared eps grid {list(config.eps_grid)}."
        )
    if ref_row is not None:
        parts.append(
            f"At the reference budget eps={ref:g} the attack success rate was "
            f"{_rate(ref_row.attack_success_rate)} "
            f"({_fraction(ref_row.n_flipped_from_clean, ref_row.n_clean_correct)}) and accuracy "
            f"{_fraction(ref_row.n_correct, ref_row.n)} [{ref_row.id}]."
        )
    if clean is not None:
        parts.append(f"Clean accuracy {_fraction(clean.n_correct, clean.n)} [{clean.id}].")
    if control is not None:
        parts.append(
            f"Benign noise control at eps={ref:g}: accuracy {_fraction(control.n_correct, control.n)} "
            f"[{control.id}]."
        )
    parts.append(
        f"Slice: n={config.n_samples}, seed={config.seed}; confidence {inputs.confidence} from "
        f"{inputs.n_clean_correct} clean-correct samples. Measured at these settings only."
    )
    return " ".join(parts)


def finding_remediation_steps(recommendations: Sequence[CandidateRecommendation]) -> str | None:
    """Spec 5.7: ``"CANDIDATE (not evaluated): ..."`` rendering of the rules-layer candidates."""
    if not recommendations:
        return None
    lines = [f"CANDIDATE ({r.validation}): {r.title}. {r.rationale}" for r in recommendations]
    return "\n".join(lines)


def _artifact_name(kind: str, location: str, attack_id: str) -> str | None:
    """A stable display name for a campaign-level artifact, or ``None`` to skip it.

    Locations are ``<project>/<run>/<file name>/<sha256>`` (the sink's key, possibly
    behind a filesystem root or an ``s3://`` prefix), so the file name is the segment
    before the digest. Per-attack curve files of another attack are skipped.
    """
    segments = [s for s in str(location).replace("\\", "/").split("/") if s]
    file_name = segments[-2] if len(segments) >= 2 and "." in segments[-2] else None
    if kind == "ml.curve":
        if file_name == "robustness_curve.png":
            return "robustness_curve.png"
        if file_name == f"{attack_id}.json":
            return "robustness_curve.json"
        if file_name is not None and file_name.endswith(".json"):
            return None
        return file_name or "robustness_curve"
    return file_name or kind


def _campaign_artifact_ids(session: Session, run_id: str, attack_id: str) -> dict[str, str]:
    from sqlalchemy import select

    from redsim.db.models import Artifact

    rows = session.execute(
        select(Artifact).where(Artifact.run_id == run_id, Artifact.kind.in_(sorted(_CAMPAIGN_ARTIFACT_KINDS)))
        .order_by(Artifact.created_at, Artifact.id)
    ).scalars().all()
    out: dict[str, str] = {}
    for row in rows:
        name = _artifact_name(str(row.kind), str(row.location), attack_id)
        if name is None:
            continue
        if name in out and out[name] != row.id:
            name = f"{name}#{str(row.sha256)[:12]}"
        out[name] = row.id
    return out


def _run_record_artifact_id(session: Session, run_id: str) -> str | None:
    from sqlalchemy import select

    from redsim.db.models import Artifact

    row = session.execute(
        select(Artifact).where(Artifact.run_id == run_id, Artifact.kind == "ml.run_record")
        .order_by(Artifact.created_at.desc(), Artifact.id.desc())
    ).scalars().first()
    return None if row is None else str(row.id)


def build_finding_detail(
    campaign: CampaignRecord, attack_id: str, inputs: FindingInputs, *, artifacts: dict[str, str] | None = None,
) -> MLFindingDetail:
    """The ``MLFindingDetail`` block for one attack of a completed campaign (spec 5.7)."""
    attacks = {attack.id: attack for attack in campaign.attacks}
    info = attacks.get(attack_id)
    measurements = finding_measurements(campaign, attack_id)
    observations = finding_observations(campaign, attack_id)
    interpretation, recommendations = _finding_statements(campaign, attack_id, observations)
    merged: dict[str, str] = {}
    for o in observations:
        for name, artifact_id in o.artifacts.items():
            merged[f"{o.id}:{name}" if name in merged and merged[name] != artifact_id else name] = artifact_id
    merged.update(artifacts or {})
    return MLFindingDetail(
        attack_id=attack_id, attack_name=info.name if info is not None else attack_id,
        norm=campaign.config.norm, eps_grid=list(campaign.config.eps_grid),
        reference_eps=campaign.config.reference_eps,
        first_success_eps=inputs.first_success_eps, asr_at_reference=inputs.asr_at_reference,
        asr_by_eps=inputs.asr_by_eps, threshold=inputs.threshold,
        measurements=measurements, observations=observations,
        interpretation=interpretation, recommendations=recommendations,
        limitations=list(campaign.limitations), artifacts=merged,
    )


def read_finding_detail(schema_blob: dict[str, Any] | None) -> MLFindingDetail | None:
    """Read the ``ml`` block of a stored finding back through the frozen schema."""
    if not schema_blob:
        return None
    block = schema_blob.get("ml")
    if not isinstance(block, dict) or not block:
        return None
    return MLFindingDetail.model_validate(block)


