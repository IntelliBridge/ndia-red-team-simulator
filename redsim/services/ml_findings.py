"""ML finding projections and follow-up action admissions.

The campaign record is the evidence authority. Follow-up actions are admitted
as child campaigns so they produce immutable evidence through the same worker.

Projection contract (spec 5.7): the worker writes ``RedsimFinding.model_dump()``
into ``Finding.schema_blob`` with ``finding_type="adversarial_ml"`` and the
``MLFindingDetail.model_dump()`` block at ``schema_blob["ml"]``; the API reads
that block back with ``MLFindingDetail.model_validate``. Every field is derived
from measured rows of the campaign record. Nothing is generated by an LLM here.
"""

from __future__ import annotations

import json
import logging
import math
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import TYPE_CHECKING, Any, Literal
from uuid import uuid4

from redsim.ml.schema import (
    CampaignRecord,
    CandidateRecommendation,
    FindingReview,
    Interpretation,
    Measurement,
    MLFindingDetail,
    Observation,
)
from redsim.ml.scoring import finding_inputs
from redsim.safety import authorize
from redsim.schema import RedsimFinding

if TYPE_CHECKING:
    from sqlalchemy.orm import Session

    from redsim.audit.chain import AuditWriter
    from redsim.config import RedsimConfig
    from redsim.ml.scoring import FindingInputs

logger = logging.getLogger(__name__)


_TERMINAL = {"succeeded", "failed", "cancelled"}
_SUPPORTED_MODALITIES = {"image", "tabular"}
# Spec 6.4: the only user-owned transition is ``open | failed -> false_positive``.
DISMISSABLE_FROM: frozenset[str] = frozenset({"open", "failed"})
DISMISSED_STATUS = "false_positive"

# Campaign-level artifact kinds that belong on every finding of the run (spec 5.7:
# robustness curve and the campaign SHAP artifacts). Both the spec 5.8 names and the
# names the worker's artifact sink derives from file names are accepted.
_CAMPAIGN_ARTIFACT_KINDS: frozenset[str] = frozenset({
    "ml.curve",
    "ml.shap.summary", "ml.shap.summary_text", "ml.shap_summary",
    "ml.shap.bar", "ml.shap.beeswarm",
    "ml.shap_bar_clean", "ml.shap_bar_adv", "ml.shap_beeswarm_clean", "ml.shap_beeswarm_adv",
})


class MLFindingAdmissionError(Exception):
    """A stable error returned by the ML finding admission routes."""

    def __init__(self, code: str, message: str, *, phase: str | None = None) -> None:
        super().__init__(message)
        self.code, self.phase = code, phase


@dataclass(frozen=True)
class FindingJobHandle:
    run_id: str
    job_ids: list[str]

    def to_response(self) -> dict[str, Any]:
        return {"run_id": self.run_id, "job_ids": self.job_ids,
                "status_url": f"/v1/runs/{self.run_id}"}


