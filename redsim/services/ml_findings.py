"""ML finding projections and follow-up action admissions.

The campaign record is the evidence authority. Follow-up actions are admitted
as child campaigns so they produce immutable evidence through the same worker.

Projection contract (spec 5.7): the worker writes ``RedsimFinding.model_dump()``
into ``Finding.schema_blob`` with ``finding_type="adversarial_ml"`` and the
``MLFindingDetail.model_dump()`` block at ``schema_blob["ml"]``; the API reads
that block back with ``MLFindingDetail.model_validate``. Every field is derived
from measured rows of the campaign record. Nothing is generated by an LLM here.
"""

