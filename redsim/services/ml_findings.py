_TERMINAL = {"succeeded", "failed", "cancelled"}
_SUPPORTED_MODALITIES = {"image", "tabular"}
# Spec 6.4: the only user-owned transition is ``open | failed -> false_positive``.
DISMISSABLE_FROM: frozenset[str] = frozenset({"open", "failed"})
DISMISSED_STATUS = "false_positive"

# Campaign-level artifact kinds that belong on every finding of the run (spec 5.7:
# robustness curve and the campaign SHAP artifacts). Both the spec 5.8 names and the
# names the worker's artifact sink derives from file names are accepted.
_CAMPAIGN_ARTIFACT_KINDS: frozenset[str] = frozenset({
    "ml.curve",
    "ml.shap.summary", "ml.shap.summary_text", "ml.shap_summary",
    "ml.shap.bar", "ml.shap.beeswarm",
    "ml.shap_bar_clean", "ml.shap_bar_adv", "ml.shap_beeswarm_clean", "ml.shap_beeswarm_adv",
})


class MLFindingAdmissionError(Exception):
    """A stable error returned by the ML finding admission routes."""

    def __init__(self, code: str, message: str, *, phase: str | None = None) -> None:
        super().__init__(message)
        self.code, self.phase = code, phase


@dataclass(frozen=True)
class FindingJobHandle:
    run_id: str
    job_ids: list[str]

    def to_response(self) -> dict[str, Any]:
        return {"run_id": self.run_id, "job_ids": self.job_ids,
                "status_url": f"/v1/runs/{self.run_id}"}


